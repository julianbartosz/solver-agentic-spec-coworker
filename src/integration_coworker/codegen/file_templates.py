def _to_class_name(name: str) -> str:
    """Convert to PascalCase class name."""
    # Handle snake_case and kebab-case
    parts = name.replace("-", "_").split("_")
    return "".join(word.title() for word in parts)


def _to_snake_case(name: str) -> str:
    """Convert to snake_case function name."""
    return name.replace("-", "_").lower()


def _to_python_type(field_type: str, nullable: bool) -> str:
    """Convert field type to Python type hint."""
    type_map = {
        "string": "str",
        "integer": "int",
        "decimal": "Decimal",
        "date": "date",
        "datetime": "datetime",
        "boolean": "bool",
        "email": "str",
        "uuid": "str",
        "json": "dict",
        "binary": "bytes",
    }
    base_type = type_map.get(field_type.lower(), "str")
    return f"Optional[{base_type}]" if nullable else base_type


def _get_parser_expression(field: FileField) -> str:
    """Get Python expression to parse field from CSV row dict."""
    name = field.name
    
    if field.field_type == "integer":
        if field.nullable:
            return f"int(row['{name}']) if row.get('{name}') else None"
        return f"int(row['{name}'])"
    
    if field.field_type == "decimal":
        if field.nullable:
            return f"Decimal(row['{name}']) if row.get('{name}') else None"
        return f"Decimal(row['{name}'])"
    
    if field.field_type == "date":
        # Handle common date formats
        format_mask = field.format_mask or "%Y-%m-%d"
        if field.nullable:
            return f"datetime.strptime(row['{name}'], '{format_mask}').date() if row.get('{name}') else None"
        return f"datetime.strptime(row['{name}'], '{format_mask}').date()"
    
    if field.field_type == "datetime":
        format_mask = field.format_mask or "%Y-%m-%dT%H:%M:%S"
        if field.nullable:
            return f"datetime.strptime(row['{name}'], '{format_mask}') if row.get('{name}') else None"
        return f"datetime.strptime(row['{name}'], '{format_mask}')"
    
    if field.field_type == "boolean":
        if field.nullable:
            return f"row.get('{name}', '').lower() in ('true', '1', 'yes', 'y') if row.get('{name}') else None"
        return f"row['{name}'].lower() in ('true', '1', 'yes', 'y')"
    
    # Default: string
    if field.nullable:
        return f"row.get('{name}') or None"
    return f"row['{name}']"


def _get_fixed_width_parser_expression(field: FileField, start: int, end: int) -> str:
    """Get Python expression to parse field from fixed-width line."""
    slice_expr = f"line[{start}:{end}].strip()"
    
    if field.field_type == "integer":
        if field.nullable:
            return f"int({slice_expr}) if {slice_expr} else None"
        return f"int({slice_expr})"
    
    if field.field_type == "decimal":
        if field.nullable:
            return f"Decimal({slice_expr}) if {slice_expr} else None"
        return f"Decimal({slice_expr})"
    
    if field.field_type == "date":
        format_mask = field.format_mask or "%Y%m%d"
        if field.nullable:
            return f"datetime.strptime({slice_expr}, '{format_mask}').date() if {slice_expr} else None"
        return f"datetime.strptime({slice_expr}, '{format_mask}').date()"
    
    if field.field_type == "datetime":
        format_mask = field.format_mask or "%Y%m%d%H%M%S"
        if field.nullable:
            return f"datetime.strptime({slice_expr}, '{format_mask}') if {slice_expr} else None"
        return f"datetime.strptime({slice_expr}, '{format_mask}')"
    
    if field.field_type == "boolean":
        if field.nullable:
            return f"{slice_expr}.lower() in ('y', '1', 't') if {slice_expr} else None"
        return f"{slice_expr}.lower() in ('y', '1', 't')"
    
    # Default: string
    if field.nullable:
        return f"{slice_expr} or None"
    return slice_expr


def _get_excel_parser_expression(field: FileField) -> str:
    """Get Python expression to parse field from Excel row_dict using _convert_value."""
    name = field.name
    field_type = field.field_type or "string"
    nullable = "True" if field.nullable else "False"
    return f"_convert_value(row_dict.get('{name}'), '{field_type}', {nullable})"


def _generate_validation_code(fields: List[FileField]) -> str:
    """Generate validation code for fields."""
    validations = []
    
    for f in fields:
        # Required field check
        if not f.nullable:
            validations.append(
                f"        if record.{f.name} is None:\n"
                f"            errors.append(f'Row {{i}}: {f.name} is required')"
            )
        
        # Regex validation
        if f.validation_regex:
            validations.append(
                f"        if record.{f.name} and not re.match(r'{f.validation_regex}', str(record.{f.name})):\n"
                f"            errors.append(f'Row {{i}}: {f.name} failed regex validation')"
            )
    
    return "\n".join(validations) if validations else ""


def _escape_delimiter(delimiter: str) -> str:
    """Escape delimiter for string literal."""
    if delimiter == "\t":
        return "\\t"
    if delimiter == "\n":
        return "\\n"
    return delimiter



"""
Code generation templates for file parsers and validators.

Provides templates and generators for creating parser code from FileSpec models.
Supports Python initially, with extensibility for other languages.
"""

from dataclasses import dataclass
from typing import Dict, List, Optional

from integration_coworker.domain.models import FileField, FileSpec, FileType


# =============================================================================
# Template Result Metadata
# =============================================================================

@dataclass
class FileParserTemplateResult:
    """
    Result of file parser generation with symbol names.
    
    This is the contract between file_templates.py and FileCodegenStrategy.
    The strategy uses these names instead of guessing symbol patterns,
    ensuring consistency between generated code and dependent artifacts
    (flows, tests).
    
    Attributes:
        code: The generated parser code
        module_basename: Base name for the module, e.g., "daily_transactions"
        record_class_name: PascalCase class name, e.g., "DailyTransactions"
        parse_func_name: Parse function name, e.g., "parse_daily_transactions"
        validate_func_name: Validate function name, e.g., "validate_daily_transactions"
        dependencies: Required packages, e.g., ["openpyxl"] for Excel
    """
    code: str
    module_basename: str
    record_class_name: str
    parse_func_name: str
    validate_func_name: str
    dependencies: List[str]



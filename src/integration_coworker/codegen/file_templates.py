def generate_csv_parser(
    file_spec: FileSpec,
    fields: List[FileField],
    language: str = "python",
) -> str:
    """
    Generate a CSV parser for the given file spec.
    
    Args:
        file_spec: The file specification
        fields: List of fields in the file
        language: Target language (default: python)
        
    Returns:
        Generated parser code as string
        
    Raises:
        NotImplementedError: If language is not supported
    """
    if language != "python":
        raise NotImplementedError(f"Language {language} not yet supported for CSV parsers")
    
    class_name = _to_class_name(file_spec.name)
    function_name = _to_snake_case(file_spec.name)
    module_name = f"parse_{function_name}"
    
    # Generate field definitions
    field_defs = []
    for f in sorted(fields, key=lambda x: x.position):
        python_type = _to_python_type(f.field_type, f.nullable)
        field_defs.append(f"    {f.name}: {python_type}")
    
    # Generate field parsing
    field_parsing = []
    for f in sorted(fields, key=lambda x: x.position):
        parser = _get_parser_expression(f)
        field_parsing.append(f"                    {f.name}={parser},")
    
    # Generate validation code
    validation = _generate_validation_code(fields)
    
    return PYTHON_CSV_PARSER_TEMPLATE.format(
        file_name=file_spec.name,
        class_name=class_name,
        function_name=function_name,
        module_name=module_name,
        encoding=file_spec.encoding or "utf-8",
        delimiter=_escape_delimiter(file_spec.delimiter or ","),
        field_definitions="\n".join(field_defs),
        field_parsing="\n".join(field_parsing),
        validation_code=validation or "        pass  # No validation rules",
    )


def generate_fixed_width_parser(
    file_spec: FileSpec,
    fields: List[FileField],
    language: str = "python",
) -> str:
    """
    Generate a fixed-width file parser for the given file spec.
    
    Args:
        file_spec: The file specification
        fields: List of fields with start_position and length
        language: Target language (default: python)
        
    Returns:
        Generated parser code as string
        
    Raises:
        NotImplementedError: If language is not supported
        ValueError: If fields don't have position/length info
    """
    if language != "python":
        raise NotImplementedError(f"Language {language} not yet supported for fixed-width parsers")
    
    # Validate fields have position info
    for f in fields:
        if f.start_position is None or f.length is None:
            raise ValueError(f"Field {f.name} missing start_position or length for fixed-width parsing")
    
    class_name = _to_class_name(file_spec.name)
    function_name = _to_snake_case(file_spec.name)
    
    # Generate field definitions
    field_defs = []
    for f in sorted(fields, key=lambda x: x.start_position or 0):
        python_type = _to_python_type(f.field_type, f.nullable)
        field_defs.append(f"    {f.name}: {python_type}")
    
    # Generate fixed-width parsing
    fixed_width_parsing = []
    for f in sorted(fields, key=lambda x: x.start_position or 0):
        start = f.start_position - 1  # Convert to 0-indexed
        end = start + f.length
        parser = _get_fixed_width_parser_expression(f, start, end)
        fixed_width_parsing.append(f"                    {f.name}={parser},")
    
    # Generate validation code
    validation = _generate_validation_code(fields)
    
    return PYTHON_FIXED_WIDTH_PARSER_TEMPLATE.format(
        file_name=file_spec.name,
        class_name=class_name,
        function_name=function_name,
        encoding=file_spec.encoding or "utf-8",
        skip_header=str(file_spec.has_header),
        field_definitions="\n".join(field_defs),
        fixed_width_parsing="\n".join(fixed_width_parsing),
        validation_code=validation or "        pass  # No validation rules",
    )


def generate_excel_parser(
    file_spec: FileSpec,
    fields: List[FileField],
    language: str = "python",
) -> str:
    """
    Generate an Excel parser for the given file spec.
    
    Args:
        file_spec: The file specification
        fields: List of fields in the file
        language: Target language (default: python)
        
    Returns:
        Generated parser code as string
        
    Raises:
        NotImplementedError: If language is not supported
    """
    if language != "python":
        raise NotImplementedError(f"Language {language} not yet supported for Excel parsers")
    
    class_name = _to_class_name(file_spec.name)
    function_name = _to_snake_case(file_spec.name)
    module_name = f"parse_{function_name}"
    
    # Determine sheet name from file_spec metadata
    # Check for sheet_name in description or use None for first sheet
    sheet_name = getattr(file_spec, 'sheet_name', None)
    if sheet_name:
        sheet_name_default = f'"{sheet_name}"'
        sheet_name_default_display = f'"{sheet_name}"'
    else:
        sheet_name_default = "None"
        sheet_name_default_display = "first sheet"
    
    # Generate field definitions
    field_defs = []
    for f in sorted(fields, key=lambda x: x.position):
        python_type = _to_python_type(f.field_type, f.nullable)
        field_defs.append(f"    {f.name}: {python_type}")
    
    # Generate field mapping code (header name -> column index lookup)
    field_mapping_lines = []
    for f in sorted(fields, key=lambda x: x.position):
        normalized_name = f.name.strip().lower().replace(" ", "_").replace("-", "_")
        field_mapping_lines.append(
            f"    for idx, h in enumerate(headers):\n"
            f"        if h == '{normalized_name}':\n"
            f"            field_mapping['{f.name}'] = idx\n"
            f"            break"
        )
    field_mapping_code = "\n".join(field_mapping_lines)
    
    # Generate field parsing with type conversion
    field_parsing = []
    for f in sorted(fields, key=lambda x: x.position):
        parser = _get_excel_parser_expression(f)
        field_parsing.append(f"                {f.name}={parser},")
    
    # Generate validation code
    validation = _generate_validation_code(fields)
    
    return PYTHON_EXCEL_PARSER_TEMPLATE.format(
        file_name=file_spec.name,
        class_name=class_name,
        function_name=function_name,
        module_name=module_name,
        sheet_name_default=sheet_name_default,
        sheet_name_default_display=sheet_name_default_display,
        field_definitions="\n".join(field_defs),
        field_mapping_code=field_mapping_code,
        field_parsing="\n".join(field_parsing),
        validation_code=validation or "        pass  # No validation rules",
    )


def _normalize_file_type(file_type: str) -> str:
    """
    Normalize file type to canonical internal values.
    
    Maps common extensions and enum values to the canonical types
    used by generate_file_parser routing:
    - "csv", "tsv", "pipe_delimited", "other_delimited" -> as-is
    - "xlsx", "xls" -> "excel"
    - "fixed_width" -> as-is
    
    Args:
        file_type: Raw file type string (may be extension or enum value)
        
    Returns:
        Canonical file type string for routing
    """
    # Handle enum values
    if hasattr(file_type, 'value'):
        file_type = file_type.value
    
    file_type_lower = str(file_type).lower()
    
    # Map extensions to canonical types
    excel_types = {"xlsx", "xls", FileType.XLSX.value, FileType.XLS.value}
    if file_type_lower in excel_types:
        return "excel"
    
    return file_type_lower


def generate_file_parser(
    file_spec: FileSpec,
    fields: List[FileField],
    language: str = "python",
) -> str:
    """
    Generate appropriate parser based on file type.
    
    Convenience function that routes to the right generator.
    
    Args:
        file_spec: The file specification
        fields: List of fields
        language: Target language
        
    Returns:
        Generated parser code
    """
    # Normalize file type to canonical values
    file_type = _normalize_file_type(file_spec.file_type)
    
    if file_type in ("csv", "tsv", "pipe_delimited", "other_delimited"):
        return generate_csv_parser(file_spec, fields, language)
    elif file_type == "fixed_width":
        return generate_fixed_width_parser(file_spec, fields, language)
    elif file_type == "excel":
        return generate_excel_parser(file_spec, fields, language)
    else:
        raise NotImplementedError(f"Parser generation not supported for file type: {file_spec.file_type}")


def generate_file_parser_with_metadata(
    file_spec: FileSpec,
    fields: List[FileField],
    language: str = "python",
) -> FileParserTemplateResult:
    """
    Generate parser code with metadata about generated symbols.
    
    This is the preferred API for FileCodegenStrategy - it returns both the
    generated code AND the symbol names used, so dependent artifacts (flows,
    tests) can reference them without guessing.
    
    File types are normalized: "xlsx"/"xls" -> "excel" for routing.
    
    Args:
        file_spec: The file specification
        fields: List of fields
        language: Target language
        
    Returns:
        FileParserTemplateResult with code and symbol names
        
    Raises:
        NotImplementedError: If file type is not supported
    """
    # Generate the code using existing function (which handles normalization)
    code = generate_file_parser(file_spec, fields, language)
    
    # Use the same naming helpers that templates use internally
    module_basename = _to_snake_case(file_spec.name)
    class_name = _to_class_name(file_spec.name)
    parse_func = f"parse_{module_basename}"
    validate_func = f"validate_{module_basename}"
    
    # Determine dependencies based on normalized file type
    dependencies: List[str] = []
    normalized_type = _normalize_file_type(file_spec.file_type)
    
    if normalized_type == "excel":
        dependencies.append("openpyxl")
    
    return FileParserTemplateResult(
        code=code,
        module_basename=module_basename,
        record_class_name=class_name,
        parse_func_name=parse_func,
        validate_func_name=validate_func,
        dependencies=dependencies,
    )



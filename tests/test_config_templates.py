class TestGenerateDockerCompose:
    """Tests for docker-compose.yml generation."""
    
    def test_generates_valid_yaml_structure(self):
        """Should generate valid docker-compose structure."""
        result = generate_docker_compose()
        
        assert "version: '3.8'" in result
        assert "services:" in result
        assert "volumes:" in result
        assert "networks:" in result
    
    def test_includes_postgres_by_default(self):
        """Should include PostgreSQL service by default."""
        result = generate_docker_compose()
        
        assert "postgres:" in result
        assert "pgvector/pgvector:pg16" in result
        assert "POSTGRES_USER:" in result
        assert "POSTGRES_PASSWORD:" in result
        assert "postgres_data:" in result
    
    def test_excludes_postgres_when_disabled(self):
        """Should exclude PostgreSQL when include_db=False."""
        result = generate_docker_compose(include_db=False)
        
        assert "postgres:" not in result
        assert "pgvector" not in result
    
    def test_includes_redis_when_enabled(self):
        """Should include Redis when include_redis=True."""
        result = generate_docker_compose(include_redis=True)
        
        assert "redis:" in result
        assert "redis:7-alpine" in result
        assert "redis_data:" in result
    
    def test_excludes_redis_by_default(self):
        """Should exclude Redis by default."""
        result = generate_docker_compose()
        
        assert "redis:" not in result
    
    def test_includes_custom_services(self):
        """Should include custom service configurations."""
        services = [
            ServiceConfig(
                name="api",
                image="myapp:latest",
                ports=["8080:8080"],
                environment={"PORT": "8080"},
                depends_on=["postgres"],
            )
        ]
        
        result = generate_docker_compose(services=services)
        
        assert "api:" in result
        assert "myapp:latest" in result
        assert "8080:8080" in result
        assert "PORT: 8080" in result
        assert "depends_on:" in result
    
    def test_custom_network_name(self):
        """Should use custom network name."""
        result = generate_docker_compose(network_name="custom-net")
        
        assert "custom-net:" in result
    
    def test_service_with_volumes(self):
        """Should include service volumes."""
        services = [
            ServiceConfig(
                name="app",
                image="app:latest",
                volumes=["app_data:/data", "./config:/etc/app"],
            )
        ]
        
        result = generate_docker_compose(services=services, include_db=False)
        
        assert "app_data:/data" in result
        assert "./config:/etc/app" in result
        assert "app_data:" in result  # Volume definition
    
    def test_service_with_healthcheck(self):
        """Should include service healthcheck."""
        services = [
            ServiceConfig(
                name="app",
                image="app:latest",
                healthcheck={"test": ["CMD", "curl", "-f", "http://localhost/health"]},
            )
        ]
        
        result = generate_docker_compose(services=services, include_db=False)
        
        assert "healthcheck:" in result



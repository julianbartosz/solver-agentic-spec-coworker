class TestDataclasses:
    """Tests for dataclass functionality."""
    
    def test_service_config_defaults(self):
        """ServiceConfig should have sensible defaults."""
        svc = ServiceConfig(name="test", image="test:latest")
        
        assert svc.ports == []
        assert svc.environment == {}
        assert svc.volumes == []
        assert svc.depends_on == []
        assert svc.command is None
        assert svc.healthcheck is None
    
    def test_env_variable_defaults(self):
        """EnvVariable should have sensible defaults."""
        var = EnvVariable(name="TEST", description="Test var")
        
        assert var.default is None
        assert var.required is True
        assert var.secret is False
    
    def test_service_config_with_all_fields(self):
        """ServiceConfig should accept all fields."""
        svc = ServiceConfig(
            name="app",
            image="app:latest",
            ports=["8080:8080"],
            environment={"DEBUG": "true"},
            volumes=["data:/data"],
            depends_on=["db"],
            command="python main.py",
            healthcheck={"test": ["CMD", "curl", "-f", "http://localhost/health"]},
        )
        
        assert svc.name == "app"
        assert svc.command == "python main.py"
        assert "DEBUG" in svc.environment

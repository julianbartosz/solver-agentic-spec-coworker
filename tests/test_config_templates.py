class TestGenerateEnvTemplate:
    """Tests for .env.template generation."""
    
    def test_includes_header_comments(self):
        """Should include descriptive header comments."""
        result = generate_env_template()
        
        assert "# Integration Configuration" in result
        assert "Generated by integration_coworker" in result
        assert "Copy this file to .env" in result
    
    def test_includes_db_vars_by_default(self):
        """Should include database variables by default."""
        result = generate_env_template()
        
        assert "POSTGRES_USER=" in result
        assert "POSTGRES_PASSWORD=" in result
        assert "POSTGRES_DB=" in result
        assert "DATABASE_URL=" in result
    
    def test_excludes_db_vars_when_disabled(self):
        """Should exclude database variables when disabled."""
        result = generate_env_template(include_db=False)
        
        assert "POSTGRES_USER" not in result
        assert "DATABASE_URL" not in result
    
    def test_includes_llm_vars_by_default(self):
        """Should include LLM API variables by default."""
        result = generate_env_template()
        
        assert "OPENAI_API_KEY=" in result
        assert "AZURE_OPENAI" in result
    
    def test_excludes_llm_vars_when_disabled(self):
        """Should exclude LLM variables when disabled."""
        result = generate_env_template(include_llm=False)
        
        assert "OPENAI_API_KEY" not in result
    
    def test_includes_source_system_bearer_auth(self):
        """Should include bearer token for source system."""
        source = SourceSystem(
            id=1,
            code="stripe",
            name="Stripe",
            auth_type="bearer",
        )
        
        result = generate_env_template(source_system=source)
        
